#!/usr/bin/env node
// 从 pptx-ops 的 prompts/ops/*.md 生成目录快照。
// 这样 tools/plan 不依赖 vendor 的 ?raw import，typecheck 也不需要解析 .md。

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const docsDir = resolve(root, '../../vendor/genoffice/packages/pptx-ops/src/prompts/ops')
const GROUP_ORDER = ['text', 'element', 'insert', 'table', 'slide', 'deck']
const HEADING_RE = /^### ([A-Za-z][A-Za-z0-9]*)(?:\s+\(([^)]*)\))?\s*$/
const SIG_RE = /^`([^`]+)`\s*$/
const FENCE_JSON_RE = /^```json\s*$/
const FENCE_END_RE = /^```\s*$/

function parseGroup(group, md) {
  const lines = md.split(/\r?\n/)
  let title = ''
  let summary = ''
  let firstBlock = -1
  for (let i = 0; i < lines.length; i++) {
    if (HEADING_RE.test(lines[i])) {
      firstBlock = i
      break
    }
    const line = lines[i]
    if (!title && line.startsWith('# ')) title = line.slice(2).trim()
    else if (title && !summary && line.startsWith('> ')) summary = line.slice(2).trim()
  }
  if (firstBlock < 0) throw new Error(`${group}: no op blocks`)
  const header = lines.slice(0, firstBlock).join('\n').trimEnd()

  const blocks = []
  let i = firstBlock
  while (i < lines.length) {
    const heading = HEADING_RE.exec(lines[i])
    if (!heading) {
      i++
      continue
    }
    const name = heading[1]
    const flags = (heading[2] ?? '')
      .split(',')
      .map((f) => f.trim())
      .filter(Boolean)
    const start = i
    i++
    while (i < lines.length && lines[i].trim() === '') i++
    const sigMatch = i < lines.length ? SIG_RE.exec(lines[i]) : null
    if (!sigMatch) throw new Error(`${group}: ${name} missing signature`)
    const sig = sigMatch[1]
    i++
    const bodyLines = []
    const examples = []
    let fence = null
    while (i < lines.length && !HEADING_RE.test(lines[i])) {
      const line = lines[i]
      if (fence) {
        if (FENCE_END_RE.test(line)) {
          examples.push(fence.join('\n'))
          fence = null
        } else fence.push(line)
      } else if (FENCE_JSON_RE.test(line)) {
        fence = []
      }
      bodyLines.push(line)
      i++
    }
    if (fence) throw new Error(`${group}: ${name} unterminated json fence`)
    blocks.push({
      name,
      group,
      sig,
      body: bodyLines.join('\n').trim(),
      examples,
      aiCallable: flags.includes('not-ai-callable') ? false : undefined,
      pending: flags.includes('pending') ? true : undefined,
      raw: lines.slice(start, i).join('\n').trimEnd(),
      hidden: flags.includes('not-ai-callable') || flags.includes('pending'),
    })
  }

  const visible = blocks.filter((b) => !b.hidden)
  const guide = [header, ...visible.map((b) => b.raw)].filter(Boolean).join('\n\n')
  return { group, title, summary, blocks, guide }
}

const groups = []
for (const group of GROUP_ORDER) {
  const md = await readFile(join(docsDir, `${group}.md`), 'utf8')
  groups.push(parseGroup(group, md))
}

const docs = {}
for (const item of groups) {
  for (const block of item.blocks) {
    docs[block.name] = {
      sig: block.sig,
      group: block.group,
      body: block.body,
      examples: block.examples,
      ...(block.aiCallable === false ? { aiCallable: false } : {}),
      ...(block.pending ? { pending: true } : {}),
    }
  }
}

const guides = Object.fromEntries(groups.map((g) => [g.group, g.guide]))
const summaries = Object.fromEntries(groups.map((g) => [g.group, g.summary]))
const titles = Object.fromEntries(groups.map((g) => [g.group, g.title]))

const out = `// AUTO-GENERATED by scripts/gen-op-catalog.mjs. Do not edit by hand.
// Source: vendor/genoffice/packages/pptx-ops/src/prompts/ops/*.md

export interface OpDoc {
  sig: string
  group: string
  body: string
  examples: string[]
  aiCallable?: false
  pending?: true
}

export const OP_GROUPS = ${JSON.stringify(GROUP_ORDER)} as const
export const OP_TITLES: Record<string, string> = ${JSON.stringify(titles, null, 2)}
export const OP_SUMMARIES: Record<string, string> = ${JSON.stringify(summaries, null, 2)}
export const OP_DOCS: Record<string, OpDoc> = ${JSON.stringify(docs, null, 2)}
export const OP_GUIDES: Record<string, string> = ${JSON.stringify(guides, null, 2)}
`

await writeFile(join(root, 'src/tools/op-catalog.generated.ts'), out)
console.log(`generated op catalog: ${Object.keys(docs).length} ops, ${GROUP_ORDER.length} groups`)
